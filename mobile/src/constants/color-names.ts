// The swatch for a typed name: an exact match ("Lavender"), else its last word
// ("Frost Green" -> green), else null. Spaces and dashes don't matter.
export function colorForName(name: string): string | null {
  const clean = name.trim().toLowerCase().replace(/[-_]+/g, " ").replace(/\s+/g, " ");
  if (!clean) return null;
  const squashed = (text: string) => text.replace(/ /g, "");
  const exact = COLOR_NAMES[clean] ?? COLOR_NAMES[squashed(clean)];
  if (exact) return exact;
  const words = clean.split(" ");
  return words.length > 1 ? (COLOR_NAMES[words[words.length - 1]] ?? null) : null;
}

// Both swatches for a two-tone name ("White/Black"), or null if it isn't one
export function colorsForTwoTone(name: string): [string, string] | null {
  const parts = name.split("/");
  if (parts.length !== 2) return null;
  const first = colorForName(parts[0]);
  const second = colorForName(parts[1]);
  return first && second ? [first, second] : null;
}

